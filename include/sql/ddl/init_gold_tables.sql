CREATE TABLE IF NOT EXISTS DIM_DAY (
    DAY_KY          NUMBER(8,0)     NOT NULL,
    CALENDAR_DT     DATE            NOT NULL,
    DAY_OF_WEEK_NM  VARCHAR(10),
    DAY_OF_WEEK_NUM NUMBER(1,0),
    WEEK_NUM        NUMBER(2,0),
    MONTH_NUM       NUMBER(2,0),
    MONTH_NM        VARCHAR(10),
    QUARTER_NUM     NUMBER(1,0),
    YEAR_NUM        NUMBER(4,0),
    IS_WEEKEND      CHAR(1)         DEFAULT 'N',
    IS_HOLIDAY      CHAR(1)         DEFAULT 'N',
    REC_INS_TS      TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_dim_day PRIMARY KEY (DAY_KY),
    CONSTRAINT uq_dim_day_dt UNIQUE (CALENDAR_DT)
);

DELETE FROM DIM_DAY;

INSERT INTO DIM_DAY (
    DAY_KY, CALENDAR_DT, DAY_OF_WEEK_NM, DAY_OF_WEEK_NUM,
    WEEK_NUM, MONTH_NUM, MONTH_NM, QUARTER_NUM, YEAR_NUM, IS_WEEKEND
)
SELECT
    TO_NUMBER(TO_CHAR(dt, 'YYYYMMDD'))          AS DAY_KY,
    dt                                          AS CALENDAR_DT,
    DAYNAME(dt)                                 AS DAY_OF_WEEK_NM,
    DAYOFWEEKISO(dt)                            AS DAY_OF_WEEK_NUM,
    WEEKOFYEAR(dt)                              AS WEEK_NUM,
    MONTH(dt)                                   AS MONTH_NUM,
    MONTHNAME(dt)                               AS MONTH_NM,
    QUARTER(dt)                                 AS QUARTER_NUM,
    YEAR(dt)                                    AS YEAR_NUM,
    IFF(DAYOFWEEKISO(dt) IN (6, 7), 'Y', 'N')  AS IS_WEEKEND
FROM (

    SELECT DATEADD(day, SEQ4(), '2026-03-01'::DATE) AS dt
    FROM TABLE(GENERATOR(ROWCOUNT => 5))
)
WHERE dt <= '2026-03-05'::DATE;

