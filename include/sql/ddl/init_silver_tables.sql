CREATE TABLE IF NOT EXISTS TMP_POS_SALES (
    TXN_ID          VARCHAR(100)    NOT NULL,
    LINE_ID         VARCHAR(100)    NOT NULL,
    TXN_TS          TIMESTAMP_NTZ   NOT NULL,
    TXN_DT          DATE            NOT NULL,
    STORE_ID        VARCHAR(50)     NOT NULL,
    ITEM_ID         VARCHAR(50)     NOT NULL,
    SLS_QTY         NUMBER(18,4)    NOT NULL DEFAULT 0,
    SLS_AMT         NUMBER(18,4)    NOT NULL DEFAULT 0,
    RTN_QTY         NUMBER(18,4)    NOT NULL DEFAULT 0,
    RTN_AMT         NUMBER(18,4)    NOT NULL DEFAULT 0,

    SRC_FILE_NM     VARCHAR(255),
    SRC_ROW_NUM     NUMBER(18,0),
    BATCH_ID        VARCHAR(200),

    CONSTRAINT uix_tmp_pos_key UNIQUE (TXN_ID, LINE_ID, TXN_DT)
);

CREATE TABLE IF NOT EXISTS TMP_INVENTORY (
    STORE_ID            VARCHAR(50)     NOT NULL,
    ITEM_ID             VARCHAR(50)     NOT NULL,
    SNAP_DT             DATE            NOT NULL,
    STOCK_ON_HAND       NUMBER(18,4)    NOT NULL DEFAULT 0,
    STOCK_IN_TRANSIT    NUMBER(18,4)    NOT NULL DEFAULT 0,
    STOCK_RESERVED      NUMBER(18,4)    NOT NULL DEFAULT 0,
    SRC_FILE_NM         VARCHAR(255),
    SRC_ROW_NUM         NUMBER(18,0),
    BATCH_ID            VARCHAR(200),
    CONSTRAINT uix_tmp_inv_key UNIQUE (STORE_ID, ITEM_ID, SNAP_DT)
);

CREATE TABLE IF NOT EXISTS TMP_ITEM (
    ITEM_ID         VARCHAR(50)     NOT NULL,
    ITEM_DESC       VARCHAR(500),
    SUBCLASS_ID     VARCHAR(50),
    SUBCLASS_NM     VARCHAR(255),
    CLASS_ID        VARCHAR(50),
    CLASS_NM        VARCHAR(255),
    DEPT_ID         VARCHAR(50),
    DEPT_NM         VARCHAR(255),
    UNIT_COST       NUMBER(18,4),
    UNIT_RETAIL     NUMBER(18,4),
    SRC_FILE_NM     VARCHAR(255),
    INGEST_DT       DATE,
    CONSTRAINT pk_tmp_item PRIMARY KEY (ITEM_ID)
);

CREATE TABLE IF NOT EXISTS TMP_SUBCLASS (
    SUBCLASS_ID     VARCHAR(50)     NOT NULL,
    SUBCLASS_NM     VARCHAR(255),
    CLASS_ID        VARCHAR(50),
    CLASS_NM        VARCHAR(255),
    DEPT_ID         VARCHAR(50),
    DEPT_NM         VARCHAR(255),
    INGEST_DT       DATE,
    CONSTRAINT pk_tmp_subclass PRIMARY KEY (SUBCLASS_ID)
);

CREATE TABLE IF NOT EXISTS TMP_LOCN (
    LOCN_ID         VARCHAR(50)     NOT NULL,
    LOCN_NM         VARCHAR(255),
    DISTRICT_ID     VARCHAR(50),
    DISTRICT_NM     VARCHAR(255),
    REGION_ID       VARCHAR(50),
    REGION_NM       VARCHAR(255),
    STORE_TYPE      VARCHAR(50),
    OPEN_DT         DATE,
    CLOSE_DT        DATE,
    SRC_FILE_NM     VARCHAR(255),
    INGEST_DT       DATE,
    CONSTRAINT pk_tmp_locn PRIMARY KEY (LOCN_ID)
);

CREATE TABLE IF NOT EXISTS TMP_DISTRICT (
    DISTRICT_ID     VARCHAR(50)     NOT NULL,
    DISTRICT_NM     VARCHAR(255),
    REGION_ID       VARCHAR(50),
    REGION_NM       VARCHAR(255),
    INGEST_DT       DATE,
    CONSTRAINT pk_tmp_district PRIMARY KEY (DISTRICT_ID)
);
