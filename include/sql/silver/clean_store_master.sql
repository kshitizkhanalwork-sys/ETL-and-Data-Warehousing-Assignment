TRUNCATE TABLE TMP_LOCN;

INSERT INTO TMP_LOCN (
    LOCN_ID,
    LOCN_NM,
    DISTRICT_ID,
    DISTRICT_NM,
    REGION_ID,
    REGION_NM,
    STORE_TYPE,
    OPEN_DT,
    CLOSE_DT,
    SRC_FILE_NM,
    INGEST_DT
)
SELECT
    TRIM(NULLIF(STORE_ID,     ''))              AS LOCN_ID,
    TRIM(NULLIF(STORE_NM,     ''))              AS LOCN_NM,
    TRIM(NULLIF(DISTRICT_ID,  ''))              AS DISTRICT_ID,
    TRIM(NULLIF(DISTRICT_NM,  ''))              AS DISTRICT_NM,
    TRIM(NULLIF(REGION_ID,    ''))              AS REGION_ID,
    TRIM(NULLIF(REGION_NM,    ''))              AS REGION_NM,
    TRIM(NULLIF(STORE_TYPE,   ''))              AS STORE_TYPE,

    TRY_TO_DATE(TRIM(OPEN_DT),  'YYYY-MM-DD')  AS OPEN_DT,
    TRY_TO_DATE(TRIM(CLOSE_DT), 'YYYY-MM-DD')  AS CLOSE_DT,
    SRC_FILE_NM,
    INGEST_DT
FROM STG_STORE_MASTER
WHERE INGEST_DT = '{logical_date}'::DATE

  AND NULLIF(TRIM(STORE_ID), '') IS NOT NULL;

TRUNCATE TABLE TMP_DISTRICT;

INSERT INTO TMP_DISTRICT (
    DISTRICT_ID,
    DISTRICT_NM,
    REGION_ID,
    REGION_NM,
    INGEST_DT
)
SELECT DISTINCT
    DISTRICT_ID,
    DISTRICT_NM,
    REGION_ID,
    REGION_NM,
    INGEST_DT
FROM TMP_LOCN
WHERE DISTRICT_ID IS NOT NULL;
